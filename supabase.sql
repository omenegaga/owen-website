-- Run this in Supabase SQL Editor.
create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  first_name text not null check (char_length(trim(first_name)) between 1 and 80),
  email text not null check (char_length(email) <= 254),
  created_at timestamptz not null default now(),
  landing_page_url text,
  referrer text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  utm_term text,
  utm_content text,
  fbclid text
);

alter table public.leads enable row level security;

-- Public visitors can submit a lead, but cannot read, update, or delete leads.
drop policy if exists "Allow public lead submissions" on public.leads;
create policy "Allow public lead submissions"
on public.leads for insert
to anon, authenticated
with check (
  char_length(trim(first_name)) between 1 and 80
  and char_length(email) between 3 and 254
);

create index if not exists leads_created_at_idx on public.leads (created_at desc);
create index if not exists leads_email_idx on public.leads (lower(email));
